#!/usr/bin/env node
/**
 * Keeps the runtime translation dictionaries in sync with the dictionary
 * embedded in app.js (the original Study Zone i18n source of truth) and the
 * additive `extra.*.json` files used by the Android/offline features.
 */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const appPath = path.join(root, "app.js");
const localesDir = path.join(root, "locales");
fs.mkdirSync(localesDir, { recursive: true });

const source = fs.readFileSync(appPath, "utf8");
const start = source.indexOf("const interfaceText = {");
if (start < 0) throw new Error("interfaceText dictionary not found");
let index = source.indexOf("{", start);
let depth = 0;
let end = -1;
for (let i = index; i < source.length; i += 1) {
  const char = source[i];
  if (char === "{") depth += 1;
  else if (char === "}") {
    depth -= 1;
    if (depth === 0) {
      end = i + 1;
      break;
    }
  }
}
if (end < 0) throw new Error("interfaceText dictionary is not balanced");
const literal = source.slice(index, end);
const base = vm.runInNewContext(`(${literal})`, Object.create(null));

const readJson = (file, fallback) => {
  const full = path.join(localesDir, file);
  if (!fs.existsSync(full)) return fallback;
  return JSON.parse(fs.readFileSync(full, "utf8"));
};

const extraAr = readJson("extra.ar.json", {});
const extraEn = readJson("extra.en.json", {});
const ar = { ...base, ...extraAr };
const en = {};
for (const key of Object.keys(ar)) en[key] = extraEn[key] || key;

fs.writeFileSync(
  path.join(localesDir, "ar.json"),
  `${JSON.stringify(ar, null, 2)}\n`,
);
fs.writeFileSync(
  path.join(localesDir, "en.json"),
  `${JSON.stringify(en, null, 2)}\n`,
);

const runtime = `/* Generated by scripts/extract-locales.js — do not edit by hand. */
window.studyZoneLocales = {
  en: ${JSON.stringify(en)},
  ar: ${JSON.stringify(ar)},
};
`;
fs.writeFileSync(path.join(localesDir, "..", "locales.js"), runtime);
console.log(
  `[locales] ${Object.keys(ar).length} keys written to locales/ar.json, locales/en.json and locales.js`,
);
